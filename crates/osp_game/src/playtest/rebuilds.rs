//! The craft the game ships, each built again from nothing in the builder, as a player would build
//! it from the parts list, and launched. What it launched (`craft.json`) is the craft file.

use bevy::input::keyboard::KeyCode;

use super::{Play, Playtest, Spot};

/// A sandbox started from the title screen and a new vessel in the builder, then these steps; then
/// launched. On the pad it lifts off on full throttle with SAS on; in orbit it is only put there; on
/// the runway (a plane, from the Hangar) it rolls on full throttle.
macro_rules! in_the_builder {
    (pad; $($step:expr),* $(,)?) => {
        in_the_builder!(@build "vehicle_assembly", "editor.new", [$($step),*], [
            Play::Click(Spot::Ui("editor.launch")),
            Play::Until("!ui.shown.editor", 20.0),
            Play::Picture("pad.png"),
            Play::Goal("on the pad"),
            Play::Key(KeyCode::KeyT),
            Play::Key(KeyCode::KeyZ),
            Play::Key(KeyCode::Space),
            Play::Track("vessel.altitude", "height, m"),
            Play::Track("vessel.twr", "thrust to weight"),
            Play::Until("vessel.altitude > 100", 30.0),
            Play::Goal("liftoff"),
        ])
    };
    (orbit; $($step:expr),* $(,)?) => {
        in_the_builder!(@build "vehicle_assembly", "editor.new", [$($step),*], [
            Play::Click(Spot::Ui("editor.place:orbit")),
            Play::Click(Spot::Ui("editor.launch")),
            Play::Until("!ui.shown.editor", 20.0),
            Play::Picture("orbit.png"),
            Play::Goal("in orbit"),
        ])
    };
    (runway; $($step:expr),* $(,)?) => {
        in_the_builder!(@build "hangar", "editor.new:plane", [$($step),*], [
            Play::Click(Spot::Ui("editor.launch")),
            Play::Until("!ui.shown.editor", 20.0),
            Play::Picture("runway.png"),
            Play::Goal("on the runway"),
            Play::Key(KeyCode::KeyZ),
            Play::Key(KeyCode::Space),
            Play::Track("nav.speed", "speed, m/s"),
            Play::Until("nav.speed > 20", 30.0),
            Play::Picture("rolling.png"),
            Play::Goal("rolling"),
        ])
    };
    (@build $building:literal, $new:literal, [$($step:expr),* $(,)?], [$($end:expr),* $(,)?]) => {
        &[
            Play::Until("menu.screen == title", 60.0),
            Play::Click(Spot::Ui("menu.open:new_game")),
            Play::Until("menu.screen == new_game", 5.0),
            Play::Click(Spot::Ui("ask.leave:game.new")),
            Play::Until("centre.open", 20.0),
            Play::Click(Spot::Building($building)),
            Play::Until("ui.shown.editor", 20.0),
            Play::Click(Spot::Ui($new)),
            Play::Until("editor.has_vessel", 5.0),
            $($step,)*
            $($end,)*
        ]
    };
}

